#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum SaturatingOperation {
    Add,
    Subtract,
    Multiply,
}

fn collect_saturating_operations(
    program: &Program,
    model: &SemanticModel,
) -> BTreeSet<(IntType, SaturatingOperation)> {
    fn visit_block(
        block: &Block,
        model: &SemanticModel,
        used: &mut BTreeSet<(IntType, SaturatingOperation)>,
    ) {
        for statement in &block.statements {
            match statement {
                Stmt::Let { value, .. } => visit_expression(value, model, used),
                Stmt::Const(declaration) => visit_expression(&declaration.value, model, used),
                Stmt::Expr(expression) => visit_expression(expression, model, used),
                Stmt::Defer(block, _) => visit_block(block, model, used),
            }
        }
        if let Some(tail) = block.tail.as_deref() {
            visit_expression(tail, model, used);
        }
    }

    fn visit_expression(
        expression: &Expr,
        model: &SemanticModel,
        used: &mut BTreeSet<(IntType, SaturatingOperation)>,
    ) {
        match &expression.kind {
            ExprKind::Binary {
                operator,
                left,
                right,
            } => {
                let operation = match operator {
                    BinaryOp::SaturatingAdd => Some(SaturatingOperation::Add),
                    BinaryOp::SaturatingSubtract => Some(SaturatingOperation::Subtract),
                    BinaryOp::SaturatingMultiply => Some(SaturatingOperation::Multiply),
                    _ => None,
                };
                if let Some(operation) = operation {
                    if let Some(Type::Int(kind)) = model.expression_types.get(&expression.id) {
                        used.insert((*kind, operation));
                    }
                }
                visit_expression(left, model, used);
                visit_expression(right, model, used);
            }
            ExprKind::Assign {
                operator,
                target,
                value,
            } => {
                let operation = match operator {
                    AssignOp::SaturatingAdd => Some(SaturatingOperation::Add),
                    AssignOp::SaturatingSubtract => Some(SaturatingOperation::Subtract),
                    AssignOp::SaturatingMultiply => Some(SaturatingOperation::Multiply),
                    _ => None,
                };
                if let Some(operation) = operation {
                    if let Some(Type::Int(kind)) = model.expression_types.get(&target.id) {
                        used.insert((*kind, operation));
                    }
                }
                visit_expression(target, model, used);
                visit_expression(value, model, used);
            }
            ExprKind::Block(block) => visit_block(block, model, used),
            ExprKind::If {
                condition,
                then_block,
                else_expr,
            } => {
                visit_expression(condition, model, used);
                visit_block(then_block, model, used);
                if let Some(else_expr) = else_expr.as_deref() {
                    visit_expression(else_expr, model, used);
                }
            }
            ExprKind::Match { value, arms } => {
                visit_expression(value, model, used);
                for arm in arms {
                    visit_expression(&arm.value, model, used);
                }
            }
            ExprKind::Try { body, arms } => {
                visit_block(body, model, used);
                for arm in arms {
                    visit_expression(&arm.value, model, used);
                }
            }
            ExprKind::While { condition, body } => {
                visit_expression(condition, model, used);
                visit_block(body, model, used);
            }
            ExprKind::For {
                initializer,
                condition,
                update,
                body,
            } => {
                if let Some(initializer) = initializer.as_deref() {
                    match initializer {
                        ForInitializer::Let { value, .. } | ForInitializer::Expr(value) => {
                            visit_expression(value, model, used);
                        }
                    }
                }
                if let Some(condition) = condition.as_deref() {
                    visit_expression(condition, model, used);
                }
                if let Some(update) = update.as_deref() {
                    visit_expression(update, model, used);
                }
                visit_block(body, model, used);
            }
            ExprKind::Call { callee, arguments } => {
                visit_expression(callee, model, used);
                for argument in arguments {
                    visit_expression(argument, model, used);
                }
            }
            ExprKind::Field { base, .. } => visit_expression(base, model, used),
            ExprKind::Propagate(value)
            | ExprKind::Unary { value, .. }
            | ExprKind::Cast { value, .. }
            | ExprKind::Raise(value) => visit_expression(value, model, used),
            ExprKind::StructLiteral { fields, .. } => {
                for field in fields {
                    visit_expression(&field.value, model, used);
                }
            }
            ExprKind::Return(value) => {
                if let Some(value) = value.as_deref() {
                    visit_expression(value, model, used);
                }
            }
            ExprKind::Literal(_)
            | ExprKind::Path(_)
            | ExprKind::TypeApply { .. }
            | ExprKind::Break
            | ExprKind::Continue
            | ExprKind::Error => {}
        }
    }

    let mut used = BTreeSet::new();
    for item in &program.items {
        match item {
            Item::Const(declaration) => visit_expression(&declaration.value, model, &mut used),
            Item::Function(function) => {
                if let Some(body) = &function.body {
                    visit_block(body, model, &mut used);
                }
            }
            _ => {}
        }
    }
    used
}

fn block_has_direct_break(block: &Block) -> bool {
    block.statements.iter().any(|statement| match statement {
        Stmt::Let { value, .. } => expression_has_direct_break(value),
        Stmt::Const(declaration) => expression_has_direct_break(&declaration.value),
        Stmt::Expr(expression) => expression_has_direct_break(expression),
        Stmt::Defer(_, _) => false,
    }) || block
        .tail
        .as_deref()
        .is_some_and(expression_has_direct_break)
}

fn expression_has_direct_break(expression: &Expr) -> bool {
    match &expression.kind {
        ExprKind::Break => true,
        ExprKind::Block(block) => block_has_direct_break(block),
        ExprKind::If {
            condition,
            then_block,
            else_expr,
        } => {
            expression_has_direct_break(condition)
                || block_has_direct_break(then_block)
                || else_expr
                    .as_deref()
                    .is_some_and(expression_has_direct_break)
        }
        ExprKind::Match { value, arms } => {
            expression_has_direct_break(value)
                || arms
                    .iter()
                    .any(|arm| expression_has_direct_break(&arm.value))
        }
        ExprKind::Try { body, arms } => {
            block_has_direct_break(body)
                || arms
                    .iter()
                    .any(|arm| expression_has_direct_break(&arm.value))
        }
        ExprKind::While { .. } | ExprKind::For { .. } => false,
        ExprKind::Call { callee, arguments } => {
            expression_has_direct_break(callee) || arguments.iter().any(expression_has_direct_break)
        }
        ExprKind::Field { base, .. }
        | ExprKind::Propagate(base)
        | ExprKind::Unary { value: base, .. }
        | ExprKind::Cast { value: base, .. }
        | ExprKind::Raise(base) => expression_has_direct_break(base),
        ExprKind::Binary { left, right, .. } => {
            expression_has_direct_break(left) || expression_has_direct_break(right)
        }
        ExprKind::Assign { target, value, .. } => {
            expression_has_direct_break(target) || expression_has_direct_break(value)
        }
        ExprKind::StructLiteral { fields, .. } => fields
            .iter()
            .any(|field| expression_has_direct_break(&field.value)),
        ExprKind::Return(value) => value.as_deref().is_some_and(expression_has_direct_break),
        ExprKind::Literal(_)
        | ExprKind::Path(_)
        | ExprKind::TypeApply { .. }
        | ExprKind::Continue
        | ExprKind::Error => false,
    }
}

fn literal_c(literal: &Literal, ty: Option<&Type>) -> String {
    match literal {
        Literal::Int(raw) => integer_c(raw, ty),
        Literal::Float(raw) => raw
            .strip_suffix("f32")
            .or_else(|| raw.strip_suffix("f64"))
            .unwrap_or(raw)
            .replace('_', ""),
        Literal::Bool(value) => value.to_string(),
        Literal::Null => "NULL".to_owned(),
        Literal::String(value) => {
            let content = decode_quoted(value, "").expect("validated string literal");
            format!(
                "((altc_str){{(const uint8_t *){}, sizeof({}) - 1u}})",
                c_string(&content),
                c_string(&content)
            )
        }
        Literal::CString(value) => {
            let content = decode_quoted(value, "c").expect("validated C string literal");
            c_string(&content)
        }
        Literal::Char(value) => {
            let content = decode_quoted(value, "").expect("validated character literal");
            let scalar = content.chars().next().expect("one character") as u32;
            format!("UINT32_C({scalar})")
        }
    }
}

fn integer_c(raw: &str, ty: Option<&Type>) -> String {
    let (value, _) = parse_integer(raw).expect("validated integer literal");
    let Some(Type::Int(kind)) = ty else {
        return value.to_string();
    };
    let macro_name = if kind.is_unsigned() {
        "UINT64_C"
    } else {
        "INT64_C"
    };
    format!("(({}){macro_name}({value}))", c_type(&Type::Int(*kind)))
}

fn signed_minimum_c(value: &Expr, ty: &Type) -> Option<String> {
    let ExprKind::Literal(Literal::Int(raw)) = &value.kind else {
        return None;
    };
    let Type::Int(kind) = ty else {
        return None;
    };
    if kind.is_unsigned() {
        return None;
    }
    let (magnitude, _) = parse_integer(raw).ok()?;
    let (expected, constant) = match kind {
        IntType::I8 => (i8::MAX as u128 + 1, "INT8_MIN"),
        IntType::I16 => (i16::MAX as u128 + 1, "INT16_MIN"),
        IntType::I32 => (i32::MAX as u128 + 1, "INT32_MIN"),
        IntType::I64 => (i64::MAX as u128 + 1, "INT64_MIN"),
        IntType::Isize => (isize::MAX as u128 + 1, "PTRDIFF_MIN"),
        IntType::CChar => (std::ffi::c_char::MAX as u128 + 1, "CHAR_MIN"),
        IntType::CSChar => (std::ffi::c_schar::MAX as u128 + 1, "SCHAR_MIN"),
        IntType::CShort => (std::ffi::c_short::MAX as u128 + 1, "SHRT_MIN"),
        IntType::CInt => (std::ffi::c_int::MAX as u128 + 1, "INT_MIN"),
        IntType::CLong => (std::ffi::c_long::MAX as u128 + 1, "LONG_MIN"),
        IntType::CLongLong => (std::ffi::c_longlong::MAX as u128 + 1, "LLONG_MIN"),
        _ => return None,
    };
    (magnitude == expected).then(|| format!("(({}){constant})", c_type(ty)))
}

fn c_string(value: &str) -> String {
    let mut output = String::from("\"");
    for byte in value.as_bytes() {
        match byte {
            b'\\' => output.push_str("\\\\"),
            b'"' => output.push_str("\\\""),
            b'\n' => output.push_str("\\n"),
            b'\r' => output.push_str("\\r"),
            b'\t' => output.push_str("\\t"),
            0x20..=0x7e => output.push(char::from(*byte)),
            byte => output.push_str(&format!("\\{byte:03o}")),
        }
    }
    output.push('"');
    output
}

fn unary_c(operator: UnaryOp) -> &'static str {
    match operator {
        UnaryOp::Not => "!",
        UnaryOp::BitNot => "~",
        UnaryOp::Plus => "+",
        UnaryOp::Negate => "-",
        UnaryOp::Address => "&",
        UnaryOp::Dereference => "*",
    }
}

fn binary_c(operator: BinaryOp) -> &'static str {
    match operator {
        BinaryOp::LogicalOr => "||",
        BinaryOp::LogicalAnd => "&&",
        BinaryOp::BitOr => "|",
        BinaryOp::BitXor => "^",
        BinaryOp::BitAnd => "&",
        BinaryOp::Equal => "==",
        BinaryOp::NotEqual => "!=",
        BinaryOp::Less => "<",
        BinaryOp::LessEqual => "<=",
        BinaryOp::Greater => ">",
        BinaryOp::GreaterEqual => ">=",
        BinaryOp::ShiftLeft => "<<",
        BinaryOp::ShiftRight => ">>",
        BinaryOp::Add | BinaryOp::WrapAdd | BinaryOp::SaturatingAdd => "+",
        BinaryOp::Subtract | BinaryOp::WrapSubtract | BinaryOp::SaturatingSubtract => "-",
        BinaryOp::Multiply | BinaryOp::WrapMultiply | BinaryOp::SaturatingMultiply => "*",
        BinaryOp::Divide => "/",
        BinaryOp::Remainder => "%",
    }
}

fn assignment_binary(operator: AssignOp) -> BinaryOp {
    match operator {
        AssignOp::Assign | AssignOp::Add => BinaryOp::Add,
        AssignOp::Subtract => BinaryOp::Subtract,
        AssignOp::Multiply => BinaryOp::Multiply,
        AssignOp::Divide => BinaryOp::Divide,
        AssignOp::WrapAdd => BinaryOp::WrapAdd,
        AssignOp::WrapSubtract => BinaryOp::WrapSubtract,
        AssignOp::WrapMultiply => BinaryOp::WrapMultiply,
        AssignOp::SaturatingAdd => BinaryOp::SaturatingAdd,
        AssignOp::SaturatingSubtract => BinaryOp::SaturatingSubtract,
        AssignOp::SaturatingMultiply => BinaryOp::SaturatingMultiply,
    }
}

fn pattern_condition(pattern: &Pattern, value: &str, ty: &Type, model: &SemanticModel) -> String {
    match pattern {
        Pattern::Wildcard(_) | Pattern::Bind(_, _) | Pattern::Struct(_, _, _) => "true".to_owned(),
        Pattern::Null(_) => format!("({value}) == NULL"),
        Pattern::NonNull(_, _) => format!("({value}) != NULL"),
        Pattern::Literal(Literal::Bool(value_literal), _) => {
            format!("({value}) == {value_literal}")
        }
        Pattern::Literal(Literal::Int(literal), _) => {
            format!("({value}) == {}", integer_c(literal, Some(ty)))
        }
        Pattern::Path(path, _) | Pattern::Variant(path, _, _) => {
            let Some((enum_name, variant)) = split_variant(path) else {
                return "false".to_owned();
            };
            if matches!(ty, Type::Enum(name) if name == enum_name)
                && model.enums.get(enum_name).is_some_and(|info| info.repr_c)
            {
                format!(
                    "({value}) == {}_{}",
                    type_name(enum_name),
                    sanitize(variant)
                )
            } else {
                format!(
                    "({value}).tag == {}_{}",
                    tag_name(enum_name),
                    sanitize(variant)
                )
            }
        }
        _ => "false".to_owned(),
    }
}

fn enum_value(path: &[String], model: &SemanticModel) -> String {
    let Some((enum_name, variant)) = split_variant(path) else {
        return "0".to_owned();
    };
    if model.enums.get(enum_name).is_some_and(|info| info.repr_c) {
        format!("{}_{}", type_name(enum_name), sanitize(variant))
    } else {
        format!(
            "(({}){{ .tag = {}_{} }})",
            type_name(enum_name),
            tag_name(enum_name),
            sanitize(variant)
        )
    }
}

fn split_variant(path: &[String]) -> Option<(&str, &str)> {
    (path.len() == 2).then(|| (path[0].as_str(), path[1].as_str()))
}

fn type_name(name: &str) -> String {
    format!("altc_{}", sanitize(name))
}

fn tag_name(name: &str) -> String {
    format!("altc_tag_{}", sanitize(name))
}

fn local_name(name: &str) -> String {
    format!("v_{}", sanitize(name))
}

fn const_name(name: &str) -> String {
    format!("altc_const_{}", sanitize(name))
}

fn sanitize(name: &str) -> String {
    name.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect()
}

