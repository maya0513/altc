use std::collections::BTreeSet;

use crate::Analysis;
use crate::ast::*;
use crate::diagnostic::{Diagnostic, Span, position};
use crate::literal::{decode_quoted, parse_integer};
use crate::semantics::{FloatType, FunctionInfo, IntType, SemanticModel, Type};

#[derive(Clone, Debug)]
pub struct CodegenOptions {
    pub unit_name: String,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            unit_name: "main".to_owned(),
        }
    }
}

#[derive(Clone, Debug)]
pub struct GeneratedUnit {
    pub unit_name: String,
    pub source: String,
    pub public_header: Option<String>,
    pub ffi_check: Option<String>,
}

/// Generate a self-contained C11 translation unit and its auxiliary headers.
pub fn emit_c(
    analysis: &Analysis,
    options: &CodegenOptions,
) -> Result<GeneratedUnit, Vec<Diagnostic>> {
    if !analysis.succeeded() {
        return Err(vec![Diagnostic::error(
            "ALTC5001",
            "C generation requires a successful frontend analysis",
            &analysis.source.path,
            &analysis.source.text,
            Span::new(0, 0),
        )]);
    }
    let mut generator = Generator::new(analysis, options);
    generator.generate();
    if generator.diagnostics.is_empty() {
        let public_header = generator.public_header();
        let ffi_check = generator.ffi_check();
        let source = generator.output.finish();
        Ok(GeneratedUnit {
            unit_name: options.unit_name.clone(),
            source,
            public_header,
            ffi_check,
        })
    } else {
        Err(generator.diagnostics)
    }
}

struct Generator<'a> {
    analysis: &'a Analysis,
    options: &'a CodegenOptions,
    output: Writer,
    diagnostics: Vec<Diagnostic>,
}

impl<'a> Generator<'a> {
    fn new(analysis: &'a Analysis, options: &'a CodegenOptions) -> Self {
        Self {
            analysis,
            options,
            output: Writer::default(),
            diagnostics: Vec::new(),
        }
    }

    fn generate(&mut self) {
        self.output.line("/* Generated by altc. Do not edit. */");
        self.output.line("#include <stdbool.h>");
        self.output.line("#include <stddef.h>");
        self.output.line("#include <stdint.h>");
        self.output.line("#include <limits.h>");
        let mut headers = BTreeSet::new();
        for item in &self.analysis.program.items {
            if let Item::Extern(block) = item {
                headers.insert(block.header.clone());
            }
        }
        for header in headers {
            self.output.line(&format!("#include {header}"));
        }
        self.output.line("");
        self.output
            .line("typedef struct { const uint8_t *data; size_t byte_len; } altc_str;");
        self.output.line("");

        self.emit_saturating_helpers();
        self.emit_type_declarations();
        self.emit_constants();
        self.emit_function_prototypes();
        self.emit_function_bodies();
        self.emit_entry_wrapper();
    }

    fn emit_saturating_helpers(&mut self) {
        let used = collect_saturating_operations(&self.analysis.program, &self.analysis.model);
        for (kind, operation) in used {
            let ty = Type::Int(kind);
            let c_ty = c_type(&ty);
            let suffix = kind.name();
            let (minimum, maximum, unsigned) = integer_limits(kind);

            match operation {
                SaturatingOperation::Add => {
                    self.output.open(&format!(
                        "static {c_ty} altc_sat_add_{suffix}({c_ty} left, {c_ty} right) {{"
                    ));
                    if unsigned {
                        self.output
                            .open(&format!("if (left > ({maximum} - right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                    } else {
                        self.output
                            .open(&format!("if (right > 0 && left > ({maximum} - right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                        self.output
                            .open(&format!("if (right < 0 && left < ({minimum} - right)) {{"));
                        self.output.line(&format!("return {minimum};"));
                        self.output.close("}");
                    }
                    self.output.line("return left + right;");
                    self.output.close("}");
                }
                SaturatingOperation::Subtract => {
                    self.output.open(&format!(
                        "static {c_ty} altc_sat_sub_{suffix}({c_ty} left, {c_ty} right) {{"
                    ));
                    if unsigned {
                        self.output.open("if (left < right) {");
                        self.output.line("return 0;");
                        self.output.close("}");
                    } else {
                        self.output
                            .open(&format!("if (right < 0 && left > ({maximum} + right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                        self.output
                            .open(&format!("if (right > 0 && left < ({minimum} + right)) {{"));
                        self.output.line(&format!("return {minimum};"));
                        self.output.close("}");
                    }
                    self.output.line("return left - right;");
                    self.output.close("}");
                }
                SaturatingOperation::Multiply => {
                    self.output.open(&format!(
                        "static {c_ty} altc_sat_mul_{suffix}({c_ty} left, {c_ty} right) {{"
                    ));
                    if unsigned {
                        self.output
                            .open(&format!("if (right != 0 && left > ({maximum} / right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                    } else {
                        self.output.open("if (left == 0 || right == 0) {");
                        self.output.line("return 0;");
                        self.output.close("}");
                        self.output.open(&format!(
                            "if ((left == -1 && right == {minimum}) || (right == -1 && left == {minimum})) {{"
                        ));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                        self.output.open("if (left > 0) {");
                        self.output
                            .open(&format!("if (right > 0 && left > ({maximum} / right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                        self.output
                            .open(&format!("if (right < 0 && right < ({minimum} / left)) {{"));
                        self.output.line(&format!("return {minimum};"));
                        self.output.close("}");
                        self.output.reopen("} else {");
                        self.output
                            .open(&format!("if (right > 0 && left < ({minimum} / right)) {{"));
                        self.output.line(&format!("return {minimum};"));
                        self.output.close("}");
                        self.output
                            .open(&format!("if (right < 0 && left < ({maximum} / right)) {{"));
                        self.output.line(&format!("return {maximum};"));
                        self.output.close("}");
                        self.output.close("}");
                    }
                    self.output.line("return left * right;");
                    self.output.close("}");
                }
            }
            self.output.line("");
        }
    }

    fn emit_type_declarations(&mut self) {
        for item in &self.analysis.program.items {
            match item {
                Item::Struct(declaration) => {
                    self.output.line(&format!(
                        "typedef struct {} {};",
                        type_name(&declaration.name),
                        type_name(&declaration.name)
                    ));
                }
                Item::Enum(declaration) if !self.analysis.model.enums[&declaration.name].repr_c => {
                    self.output.line(&format!(
                        "typedef struct {} {};",
                        type_name(&declaration.name),
                        type_name(&declaration.name)
                    ));
                }
                _ => {}
            }
        }
        if self
            .analysis
            .program
            .items
            .iter()
            .any(|item| matches!(item, Item::Struct(_) | Item::Enum(_)))
        {
            self.output.line("");
        }

        for item in &self.analysis.program.items {
            match item {
                Item::Struct(declaration) => self.emit_struct(declaration),
                Item::Enum(declaration) => self.emit_enum(declaration),
                _ => {}
            }
        }
    }

    fn emit_struct(&mut self, declaration: &StructDecl) {
        self.output
            .open(&format!("struct {} {{", type_name(&declaration.name)));
        for field in &declaration.fields {
            let ty = self.resolve_type(&field.ty);
            self.output
                .line(&format!("{} {};", c_type(&ty), local_name(&field.name)));
        }
        self.output.close("};");
        self.output.line("");
    }

    fn emit_enum(&mut self, declaration: &EnumDecl) {
        if self.analysis.model.enums[&declaration.name].repr_c {
            self.output
                .open(&format!("typedef enum {} {{", type_name(&declaration.name)));
            for variant in &declaration.variants {
                self.output.line(&format!(
                    "{}_{},",
                    type_name(&declaration.name),
                    sanitize(&variant.name)
                ));
            }
            self.output
                .close(&format!("}} {};", type_name(&declaration.name)));
            self.output.line("");
            return;
        }

        self.output.open("typedef enum {");
        for variant in &declaration.variants {
            self.output.line(&format!(
                "{}_{},",
                tag_name(&declaration.name),
                sanitize(&variant.name)
            ));
        }
        self.output
            .close(&format!("}} {};", tag_name(&declaration.name)));
        self.output
            .open(&format!("struct {} {{", type_name(&declaration.name)));
        self.output
            .line(&format!("{} tag;", tag_name(&declaration.name)));
        if declaration
            .variants
            .iter()
            .any(|variant| !variant.payload.is_empty())
        {
            self.output.open("union {");
            for variant in &declaration.variants {
                if variant.payload.is_empty() {
                    continue;
                }
                self.output.open("struct {");
                for (index, ty) in variant.payload.iter().enumerate() {
                    let ty = self.resolve_type(ty);
                    self.output.line(&format!("{} _{index};", c_type(&ty)));
                }
                self.output
                    .close(&format!("}} {};", sanitize(&variant.name)));
            }
            self.output.close("} payload;");
        }
        self.output.close("};");
        self.output.line("");
    }

    fn emit_constants(&mut self) {
        for item in &self.analysis.program.items {
            if let Item::Const(declaration) = item {
                let ty = self.resolve_type(&declaration.ty);
                let value = self.const_expression(&declaration.value);
                self.output.line(&format!(
                    "static const {} {} = {};",
                    c_type(&ty),
                    const_name(&declaration.name),
                    value
                ));
            }
        }
        if self
            .analysis
            .program
            .items
            .iter()
            .any(|item| matches!(item, Item::Const(_)))
        {
            self.output.line("");
        }
    }

    fn emit_function_prototypes(&mut self) {
        for item in &self.analysis.program.items {
            if let Item::Function(function) = item {
                if let Some(info) = self.analysis.model.functions.get(&function.name) {
                    self.output
                        .line(&format!("{};", function_signature(info, function)));
                }
            }
        }
        self.output.line("");
    }

    fn emit_function_bodies(&mut self) {
        for item in &self.analysis.program.items {
            if let Item::Function(function) = item {
                let Some(body) = &function.body else {
                    continue;
                };
                let info = self.analysis.model.functions[&function.name].clone();
                let mut output = std::mem::take(&mut self.output);
                let source_line = position(&self.analysis.source.text, function.span.start).line;
                output.line(&format!(
                    "#line {source_line} {}",
                    c_string(&self.analysis.source.path)
                ));
                output.open(&format!("{} {{", function_signature(&info, function)));
                let mut function_generator =
                    FunctionGenerator::new(self.analysis, &mut output, &mut self.diagnostics, info);
                function_generator.emit_function_body(body);
                output.close("}");
                output.line(&format!(
                    "#line 1 {}",
                    c_string(&format!("{}.generated.c", self.options.unit_name))
                ));
                output.line("");
                self.output = output;
            }
        }
    }

    fn emit_entry_wrapper(&mut self) {
        let entry = self
            .analysis
            .program
            .items
            .iter()
            .find_map(|item| match item {
                Item::Function(function) if function.attribute("entry").is_some() => Some(function),
                _ => None,
            });
        if let Some(function) = entry {
            let info = &self.analysis.model.functions[&function.name];
            self.output.open("int main(void) {");
            self.output
                .line(&format!("return (int){}();", function_c_name(info)));
            self.output.close("}");
        }
    }

    fn public_header(&self) -> Option<String> {
        let exports: Vec<_> = self
            .analysis
            .program
            .items
            .iter()
            .filter_map(|item| match item {
                Item::Function(function) if function.export_c => Some(function),
                _ => None,
            })
            .collect();
        if exports.is_empty() {
            return None;
        }
        let guard = format!(
            "ALTC_{}_H_INCLUDED",
            sanitize(&self.options.unit_name).to_uppercase()
        );
        let mut output = Writer::default();
        output.line("/* Generated by altc. Do not edit. */");
        output.line(&format!("#ifndef {guard}"));
        output.line(&format!("#define {guard}"));
        output.line("");
        output.line("#include <stdbool.h>");
        output.line("#include <stddef.h>");
        output.line("#include <stdint.h>");
        output.line("");
        for item in &self.analysis.program.items {
            match item {
                Item::Struct(declaration)
                    if self.analysis.model.structs[&declaration.name].repr_c =>
                {
                    output.open(&format!(
                        "typedef struct {} {{",
                        type_name(&declaration.name)
                    ));
                    for field in &declaration.fields {
                        output.line(&format!(
                            "{} {};",
                            c_type(&self.resolve_type(&field.ty)),
                            local_name(&field.name)
                        ));
                    }
                    output.close(&format!("}} {};", type_name(&declaration.name)));
                    output.line("");
                }
                Item::Enum(declaration) if self.analysis.model.enums[&declaration.name].repr_c => {
                    output.open(&format!("typedef enum {} {{", type_name(&declaration.name)));
                    for variant in &declaration.variants {
                        output.line(&format!(
                            "{}_{},",
                            type_name(&declaration.name),
                            sanitize(&variant.name)
                        ));
                    }
                    output.close(&format!("}} {};", type_name(&declaration.name)));
                    output.line("");
                }
                _ => {}
            }
        }
        for function in exports {
            let info = &self.analysis.model.functions[&function.name];
            output.line(&format!("{};", exported_signature(info, function)));
        }
        output.line("");
        output.line(&format!("#endif /* {guard} */"));
        Some(output.finish())
    }

    fn ffi_check(&self) -> Option<String> {
        let blocks: Vec<_> = self
            .analysis
            .program
            .items
            .iter()
            .filter_map(|item| match item {
                Item::Extern(block) => Some(block),
                _ => None,
            })
            .collect();
        if blocks.is_empty() {
            return None;
        }
        let mut output = Writer::default();
        output.line("/* Generated by altc. Do not edit. */");
        output.line("#include <stdbool.h>");
        output.line("#include <stddef.h>");
        output.line("#include <stdint.h>");
        for block in &blocks {
            output.line(&format!("#include {}", block.header));
        }
        output.line("");
        let mut index = 0usize;
        for block in blocks {
            for function in &block.functions {
                let info = &self.analysis.model.functions[&function.name];
                let parameters = info
                    .parameters
                    .iter()
                    .map(c_type)
                    .collect::<Vec<_>>()
                    .join(", ");
                output.line(&format!(
                    "typedef {} (*altc_expected_{index})({});",
                    c_type(&info.return_type),
                    if parameters.is_empty() {
                        "void"
                    } else {
                        &parameters
                    }
                ));
                output.line(&format!(
                    "_Static_assert(_Generic(&{}, altc_expected_{index}: 1, default: 0), \"altc FFI mismatch: {}\");",
                    info.c_name, info.c_name
                ));
                index += 1;
            }
            for opaque in &block.opaque_types {
                let spelling = &self.analysis.model.opaque_types[&opaque.name];
                output.line(&format!(
                    "_Static_assert(sizeof({spelling} *) == sizeof(void *), \"altc FFI opaque type missing: {spelling}\");"
                ));
            }
        }
        Some(output.finish())
    }

    fn resolve_type(&self, reference: &TypeRef) -> Type {
        resolve_type(&self.analysis.model, reference)
    }

    fn const_expression(&self, expression: &Expr) -> String {
        match &expression.kind {
            ExprKind::Literal(literal) => literal_c(
                literal,
                self.analysis.model.expression_types.get(&expression.id),
            ),
            ExprKind::Path(path) if path.len() == 1 => const_name(&path[0]),
            ExprKind::Path(path) => enum_value(path, &self.analysis.model),
            ExprKind::Unary { operator, value } => {
                if *operator == UnaryOp::Negate {
                    if let Some(ty) = self.analysis.model.expression_types.get(&expression.id) {
                        if let Some(minimum) = signed_minimum_c(value, ty) {
                            return minimum;
                        }
                    }
                }
                format!("({}{})", unary_c(*operator), self.const_expression(value))
            }
            ExprKind::Binary {
                operator,
                left,
                right,
            } => format!(
                "({} {} {})",
                self.const_expression(left),
                binary_c(*operator),
                self.const_expression(right)
            ),
            ExprKind::Cast { value, ty } => format!(
                "(({})({}))",
                c_type(&self.resolve_type(ty)),
                self.const_expression(value)
            ),
            _ => "0 /* invalid const expression */".to_owned(),
        }
    }
}

#[derive(Clone)]
struct ErrorTarget {
    label: String,
    error_variable: String,
    scope_depth: usize,
}

#[derive(Clone)]
struct LoopTarget {
    break_label: String,
    continue_label: String,
    scope_depth: usize,
}

struct FunctionGenerator<'a, 'b> {
    analysis: &'a Analysis,
    output: &'b mut Writer,
    diagnostics: &'b mut Vec<Diagnostic>,
    info: FunctionInfo,
    temporary: usize,
    label: usize,
    scopes: Vec<Vec<Block>>,
    error_targets: Vec<ErrorTarget>,
    loop_targets: Vec<LoopTarget>,
}

impl<'a, 'b> FunctionGenerator<'a, 'b> {
    fn new(
        analysis: &'a Analysis,
        output: &'b mut Writer,
        diagnostics: &'b mut Vec<Diagnostic>,
        info: FunctionInfo,
    ) -> Self {
        Self {
            analysis,
            output,
            diagnostics,
            info,
            temporary: 0,
            label: 0,
            scopes: Vec::new(),
            error_targets: Vec::new(),
            loop_targets: Vec::new(),
        }
    }

    fn emit_function_body(&mut self, body: &Block) {
        self.push_scope();
        self.emit_statements(&body.statements);
        let tail = body.tail.as_deref();
        if self.info.error_type.is_some() {
            if self.info.return_type == Type::Unit {
                if let Some(expression) = tail {
                    self.emit_expression_statement(expression);
                }
                self.emit_cleanup_from(0);
                self.output.line("return INT32_C(0);");
            } else {
                let value =
                    tail.map_or_else(|| "0".to_owned(), |expression| self.emit_value(expression));
                let saved = self.materialize(&self.info.return_type.clone(), value);
                self.output.line(&format!("*out_value = {saved};"));
                self.emit_cleanup_from(0);
                self.output.line("return INT32_C(0);");
            }
        } else if self.info.return_type == Type::Unit {
            if let Some(expression) = tail {
                self.emit_expression_statement(expression);
            }
            self.emit_cleanup_from(0);
            self.output.line("return;");
        } else {
            let value =
                tail.map_or_else(|| "0".to_owned(), |expression| self.emit_value(expression));
            let saved = self.materialize(&self.info.return_type.clone(), value);
            self.emit_cleanup_from(0);
            self.output.line(&format!("return {saved};"));
        }
        self.scopes.pop();
    }

    fn emit_statements(&mut self, statements: &[Stmt]) {
        for statement in statements {
            match statement {
                Stmt::Let {
                    name, ty, value, ..
                } => {
                    let ty = ty
                        .as_ref()
                        .map(|ty| resolve_type(&self.analysis.model, ty))
                        .or_else(|| self.analysis.model.expression_types.get(&value.id).cloned())
                        .unwrap_or(Type::Unknown);
                    let value = self.emit_value(value);
                    self.output.line(&format!(
                        "{} {} = {};",
                        c_type(&ty),
                        local_name(name),
                        value
                    ));
                }
                Stmt::Const(declaration) => {
                    let ty = resolve_type(&self.analysis.model, &declaration.ty);
                    let value = self.emit_value(&declaration.value);
                    self.output.line(&format!(
                        "const {} {} = {};",
                        c_type(&ty),
                        local_name(&declaration.name),
                        value
                    ));
                }
                Stmt::Expr(expression) => self.emit_expression_statement(expression),
                Stmt::Defer(block, _) => {
                    self.scopes
                        .last_mut()
                        .expect("defer scope")
                        .push(block.clone());
                }
            }
        }
    }

    fn emit_expression_statement(&mut self, expression: &Expr) {
        match &expression.kind {
            ExprKind::Return(value) => self.emit_return(value.as_deref()),
            ExprKind::Raise(value) => self.emit_raise(value),
            ExprKind::Break => self.emit_loop_transfer(true),
            ExprKind::Continue => self.emit_loop_transfer(false),
            _ => {
                let value = self.emit_value(expression);
                if self.expression_type(expression) != Type::Unit && !value.is_empty() {
                    self.output.line(&format!("(void)({value});"));
                }
            }
        }
    }

    fn emit_value(&mut self, expression: &Expr) -> String {
        match &expression.kind {
            ExprKind::Literal(literal) => literal_c(
                literal,
                self.analysis.model.expression_types.get(&expression.id),
            ),
            ExprKind::Path(path) => self.emit_path(path),
            ExprKind::Block(block) => {
                self.emit_block_value(block, self.expression_type(expression))
            }
            ExprKind::If {
                condition,
                then_block,
                else_expr,
            } => self.emit_if(
                condition,
                then_block,
                else_expr.as_deref(),
                self.expression_type(expression),
            ),
            ExprKind::Match { value, arms } => {
                self.emit_match(value, arms, self.expression_type(expression))
            }
            ExprKind::Try { body, arms } => {
                self.emit_try(expression.id, body, arms, self.expression_type(expression))
            }
            ExprKind::While { condition, body } => {
                self.emit_while(condition, body);
                String::new()
            }
            ExprKind::For {
                initializer,
                condition,
                update,
                body,
            } => {
                self.emit_for(
                    initializer.as_deref(),
                    condition.as_deref(),
                    update.as_deref(),
                    body,
                );
                String::new()
            }
            ExprKind::Call { callee, arguments } => {
                self.emit_call(callee, arguments, false, expression)
            }
            ExprKind::TypeApply { path, arguments } => {
                self.emit_type_apply(path, arguments, expression.span)
            }
            ExprKind::Field {
                base,
                name,
                pointer,
            } => {
                let base = self.emit_place(base);
                let field = if name == "byte_len" {
                    "byte_len".to_owned()
                } else {
                    local_name(name)
                };
                format!("({base}){}{field}", if *pointer { "->" } else { "." })
            }
            ExprKind::Propagate(value) => {
                if let ExprKind::Call { callee, arguments } = &value.kind {
                    self.emit_call(callee, arguments, true, expression)
                } else {
                    "0".to_owned()
                }
            }
            ExprKind::Unary { operator, value } => match operator {
                UnaryOp::Address => format!("(&({}))", self.emit_place(value)),
                UnaryOp::Dereference => format!("(*({}))", self.emit_value(value)),
                UnaryOp::Negate => signed_minimum_c(value, &self.expression_type(expression))
                    .unwrap_or_else(|| format!("(-{})", self.emit_value(value))),
                _ => format!("({}{})", unary_c(*operator), self.emit_value(value)),
            },
            ExprKind::Binary {
                operator,
                left,
                right,
            } => self.emit_binary(*operator, left, right, expression),
            ExprKind::Cast { value, ty } => {
                let value = self.emit_value(value);
                format!(
                    "(({})({value}))",
                    c_type(&resolve_type(&self.analysis.model, ty))
                )
            }
            ExprKind::Assign {
                operator,
                target,
                value,
            } => {
                let place = self.emit_place(target);
                let value = self.emit_value(value);
                let ty = self.expression_type(target);
                let saved = self.materialize(&ty, value);
                if *operator == AssignOp::Assign {
                    self.output.line(&format!("{place} = {saved};"));
                } else {
                    let binary = assignment_binary(*operator);
                    let value = integer_operation(binary, &ty, &format!("({place})"), &saved);
                    self.output.line(&format!("{place} = {value};"));
                }
                String::new()
            }
            ExprKind::StructLiteral { path, fields } => {
                self.emit_struct_literal(path, fields, expression)
            }
            ExprKind::Raise(value) => {
                self.emit_raise(value);
                "0".to_owned()
            }
            ExprKind::Return(value) => {
                self.emit_return(value.as_deref());
                "0".to_owned()
            }
            ExprKind::Break => {
                self.emit_loop_transfer(true);
                String::new()
            }
            ExprKind::Continue => {
                self.emit_loop_transfer(false);
                String::new()
            }
            ExprKind::Error => "0".to_owned(),
        }
    }

    fn emit_path(&self, path: &[String]) -> String {
        if path.len() == 1 {
            if self.analysis.model.const_types.contains_key(&path[0]) {
                return const_name(&path[0]);
            }
            return local_name(&path[0]);
        }
        enum_value(path, &self.analysis.model)
    }

    fn emit_call(
        &mut self,
        callee: &Expr,
        arguments: &[Expr],
        propagate: bool,
        result_expression: &Expr,
    ) -> String {
        let (path, type_arguments): (&[String], &[TypeRef]) = match &callee.kind {
            ExprKind::Path(path) => (path, &[]),
            ExprKind::TypeApply { path, arguments } => (path, arguments),
            _ => return "0".to_owned(),
        };
        if path.len() == 2 {
            return self.emit_variant_constructor(path, arguments, result_expression);
        }
        let name = &path[0];
        if matches!(
            name.as_str(),
            "ptr_as_const"
                | "ptr_addr"
                | "ptr_cast"
                | "ptr_cast_mut"
                | "offset"
                | "ptr_from_addr"
                | "ptr_from_addr_mut"
        ) {
            return self.emit_pointer_builtin(name, type_arguments, arguments, result_expression);
        }
        let Some(info) = self.analysis.model.functions.get(name).cloned() else {
            return "0".to_owned();
        };
        let mut values = Vec::new();
        for (argument, parameter_type) in arguments.iter().zip(&info.parameters) {
            let value = self.emit_value(argument);
            values.push(self.materialize(parameter_type, value));
        }
        if info.error_type.is_some() {
            if !propagate {
                return "0".to_owned();
            }
            return self.emit_raising_call(&info, &values);
        }
        let call = format!("{}({})", function_c_name(&info), values.join(", "));
        if info.return_type == Type::Unit {
            self.output.line(&format!("{call};"));
            String::new()
        } else {
            self.materialize(&info.return_type, call)
        }
    }

    fn emit_type_apply(&mut self, path: &[String], arguments: &[TypeRef], span: Span) -> String {
        let Some(name) = path.first() else {
            return "0".to_owned();
        };
        let Some(argument) = arguments.first() else {
            return "0".to_owned();
        };
        let ty = resolve_type(&self.analysis.model, argument);
        match name.as_str() {
            "sizeof" => format!("sizeof({})", c_type(&ty)),
            "alignof" => format!("_Alignof({})", c_type(&ty)),
            _ => {
                self.error("ALTC5003", "type-applied builtin must be called", span);
                "0".to_owned()
            }
        }
    }

    fn emit_pointer_builtin(
        &mut self,
        name: &str,
        _type_arguments: &[TypeRef],
        arguments: &[Expr],
        result_expression: &Expr,
    ) -> String {
        let ty = self.expression_type(result_expression);
        let first = arguments
            .first()
            .map_or_else(|| "0".to_owned(), |argument| self.emit_value(argument));
        match name {
            "offset" => {
                let first_type = arguments
                    .first()
                    .map_or(Type::Unknown, |argument| self.expression_type(argument));
                let first = self.materialize(&first_type, first);
                let second = arguments
                    .get(1)
                    .map_or_else(|| "0".to_owned(), |argument| self.emit_value(argument));
                let second_type = arguments
                    .get(1)
                    .map_or(Type::Unknown, |argument| self.expression_type(argument));
                let second = self.materialize(&second_type, second);
                format!("(({})(({first}) + ({second})))", c_type(&ty))
            }
            "ptr_addr" => format!("((size_t)(uintptr_t)({first}))"),
            "ptr_from_addr" | "ptr_from_addr_mut" => {
                format!("(({})((uintptr_t)({first})))", c_type(&ty))
            }
            _ => format!("(({})({first}))", c_type(&ty)),
        }
    }

    fn emit_raising_call(&mut self, info: &FunctionInfo, arguments: &[String]) -> String {
        let result = (info.return_type != Type::Unit).then(|| self.new_temporary());
        let error = self.new_temporary();
        if let Some(result) = &result {
            self.output
                .line(&format!("{} {result};", c_type(&info.return_type)));
        }
        let error_type = info.error_type.clone().unwrap_or(Type::Unknown);
        self.output
            .line(&format!("{} {error};", c_type(&error_type)));
        let mut call_arguments = arguments.to_vec();
        if let Some(result) = &result {
            call_arguments.push(format!("&{result}"));
        }
        call_arguments.push(format!("&{error}"));
        let status = self.new_temporary();
        self.output.line(&format!(
            "int32_t {status} = {}({});",
            function_c_name(info),
            call_arguments.join(", ")
        ));
        self.output.open(&format!("if ({status} != INT32_C(0)) {{"));
        self.propagate_error(&error);
        self.output.close("}");
        result.unwrap_or_default()
    }

    fn emit_variant_constructor(
        &mut self,
        path: &[String],
        arguments: &[Expr],
        result: &Expr,
    ) -> String {
        let enum_name = &path[0];
        let variant = &path[1];
        let ty = self.expression_type(result);
        let temporary = self.new_temporary();
        self.output.line(&format!("{} {temporary};", c_type(&ty)));
        if self
            .analysis
            .model
            .enums
            .get(enum_name)
            .is_some_and(|info| info.repr_c)
        {
            self.output.line(&format!(
                "{temporary} = {}_{};",
                type_name(enum_name),
                sanitize(variant)
            ));
            return temporary;
        }
        self.output.line(&format!(
            "{temporary}.tag = {}_{};",
            tag_name(enum_name),
            sanitize(variant)
        ));
        for (index, argument) in arguments.iter().enumerate() {
            let value = self.emit_value(argument);
            let argument_type = self.expression_type(argument);
            let value = self.materialize(&argument_type, value);
            self.output.line(&format!(
                "{temporary}.payload.{}._{index} = {value};",
                sanitize(variant)
            ));
        }
        temporary
    }

    fn emit_struct_literal(
        &mut self,
        path: &[String],
        fields: &[FieldInitializer],
        expression: &Expr,
    ) -> String {
        let ty = self.expression_type(expression);
        let temporary = self.new_temporary();
        self.output.line(&format!("{} {temporary};", c_type(&ty)));
        for field in fields {
            let value = self.emit_value(&field.value);
            let field_type = self.expression_type(&field.value);
            let value = self.materialize(&field_type, value);
            self.output.line(&format!(
                "{temporary}.{} = {value};",
                local_name(&field.name)
            ));
        }
        let _ = path;
        temporary
    }

    fn emit_binary(
        &mut self,
        operator: BinaryOp,
        left: &Expr,
        right: &Expr,
        expression: &Expr,
    ) -> String {
        let ty = self.expression_type(expression);
        if matches!(operator, BinaryOp::LogicalAnd | BinaryOp::LogicalOr) {
            let result = self.new_temporary();
            let left_value = self.emit_value(left);
            self.output.line(&format!(
                "bool {result} = {};",
                if operator == BinaryOp::LogicalAnd {
                    "false"
                } else {
                    "true"
                }
            ));
            let condition = if operator == BinaryOp::LogicalAnd {
                left_value
            } else {
                format!("!({left_value})")
            };
            self.output.open(&format!("if ({condition}) {{"));
            let right_value = self.emit_value(right);
            self.output.line(&format!("{result} = {right_value};"));
            self.output.close("}");
            return result;
        }
        let left_type = self.expression_type(left);
        let left_value = self.emit_value(left);
        let left_value = self.materialize(&left_type, left_value);
        let right_type = self.expression_type(right);
        let right_value = self.emit_value(right);
        let right_value = self.materialize(&right_type, right_value);
        integer_operation(operator, &ty, &left_value, &right_value)
    }

    fn emit_if(
        &mut self,
        condition: &Expr,
        then_block: &Block,
        else_expr: Option<&Expr>,
        ty: Type,
    ) -> String {
        let result = (ty != Type::Unit).then(|| {
            let value = self.new_temporary();
            self.output.line(&format!("{} {value};", c_type(&ty)));
            value
        });
        let condition = self.emit_value(condition);
        self.output.open(&format!("if ({condition}) {{"));
        self.emit_block_assignment(then_block, result.as_deref());
        self.output.close("}");
        if let Some(else_expr) = else_expr {
            self.output.open("else {");
            if let ExprKind::Block(block) = &else_expr.kind {
                self.emit_block_assignment(block, result.as_deref());
            } else {
                let value = self.emit_value(else_expr);
                if let Some(result) = &result {
                    self.output.line(&format!("{result} = {value};"));
                }
            }
            self.output.close("}");
        }
        result.unwrap_or_default()
    }

    fn emit_match(&mut self, value: &Expr, arms: &[MatchArm], ty: Type) -> String {
        let value_type = self.expression_type(value);
        let scrutinee = self.emit_value(value);
        let scrutinee = self.materialize(&value_type, scrutinee);
        let result = (ty != Type::Unit).then(|| {
            let value = self.new_temporary();
            self.output.line(&format!("{} {value};", c_type(&ty)));
            value
        });
        for (index, arm) in arms.iter().enumerate() {
            let condition =
                pattern_condition(&arm.pattern, &scrutinee, &value_type, &self.analysis.model);
            if index == 0 {
                self.output.open(&format!("if ({condition}) {{"));
            } else {
                self.output.open(&format!("else if ({condition}) {{"));
            }
            self.push_scope();
            self.emit_pattern_bindings(&arm.pattern, &scrutinee, &value_type);
            let value = self.emit_value(&arm.value);
            if let Some(result) = &result {
                self.output.line(&format!("{result} = {value};"));
            }
            self.emit_cleanup_current();
            self.scopes.pop();
            self.output.close("}");
        }
        result.unwrap_or_default()
    }

    fn emit_try(
        &mut self,
        expression: ExprId,
        body: &Block,
        arms: &[MatchArm],
        ty: Type,
    ) -> String {
        let error_type = self
            .analysis
            .model
            .try_error_types
            .get(&expression)
            .cloned()
            .unwrap_or(Type::Unknown);
        let result = (ty != Type::Unit).then(|| {
            let value = self.new_temporary();
            self.output.line(&format!("{} {value};", c_type(&ty)));
            value
        });
        let error_variable = self.new_temporary();
        self.output
            .line(&format!("{} {error_variable};", c_type(&error_type)));
        let catch_label = self.new_label("catch");
        let end_label = self.new_label("try_end");
        self.error_targets.push(ErrorTarget {
            label: catch_label.clone(),
            error_variable: error_variable.clone(),
            scope_depth: self.scopes.len(),
        });
        self.emit_block_assignment(body, result.as_deref());
        self.error_targets.pop();
        self.output.line(&format!("goto {end_label};"));
        self.output.line(&format!("{catch_label}: ;"));
        for (index, arm) in arms.iter().enumerate() {
            let condition = pattern_condition(
                &arm.pattern,
                &error_variable,
                &error_type,
                &self.analysis.model,
            );
            if index == 0 {
                self.output.open(&format!("if ({condition}) {{"));
            } else {
                self.output.open(&format!("else if ({condition}) {{"));
            }
            self.push_scope();
            self.emit_pattern_bindings(&arm.pattern, &error_variable, &error_type);
            let value = self.emit_value(&arm.value);
            if let Some(result) = &result {
                self.output.line(&format!("{result} = {value};"));
            }
            self.emit_cleanup_current();
            self.scopes.pop();
            self.output.close("}");
        }
        self.output.line(&format!("{end_label}: ;"));
        result.unwrap_or_default()
    }

    fn emit_while(&mut self, condition: &Expr, body: &Block) {
        let condition_label = self.new_label("while_condition");
        let break_label = self.new_label("while_break");
        self.output.line(&format!("{condition_label}: ;"));
        let condition_value = self.emit_value(condition);
        self.output
            .line(&format!("if (!({condition_value})) goto {break_label};"));
        self.loop_targets.push(LoopTarget {
            break_label: break_label.clone(),
            continue_label: condition_label.clone(),
            scope_depth: self.scopes.len(),
        });
        self.emit_block_assignment(body, None);
        self.loop_targets.pop();
        self.output.line(&format!("goto {condition_label};"));
        self.output.line(&format!("{break_label}: ;"));
    }

    fn emit_for(
        &mut self,
        initializer: Option<&ForInitializer>,
        condition: Option<&Expr>,
        update: Option<&Expr>,
        body: &Block,
    ) {
        self.output.open("{");
        self.push_scope();
        if let Some(initializer) = initializer {
            match initializer {
                ForInitializer::Let {
                    name, ty, value, ..
                } => {
                    let ty = ty
                        .as_ref()
                        .map(|ty| resolve_type(&self.analysis.model, ty))
                        .unwrap_or_else(|| self.expression_type(value));
                    let value = self.emit_value(value);
                    self.output
                        .line(&format!("{} {} = {value};", c_type(&ty), local_name(name)));
                }
                ForInitializer::Expr(expression) => self.emit_expression_statement(expression),
            }
        }
        let condition_label = self.new_label("for_condition");
        let continue_label = self.new_label("for_continue");
        let break_label = self.new_label("for_break");
        let needs_break_label = condition.is_some() || block_has_direct_break(body);
        self.output.line(&format!("{condition_label}: ;"));
        if let Some(condition) = condition {
            let value = self.emit_value(condition);
            self.output
                .line(&format!("if (!({value})) goto {break_label};"));
        }
        self.loop_targets.push(LoopTarget {
            break_label: break_label.clone(),
            continue_label: continue_label.clone(),
            scope_depth: self.scopes.len(),
        });
        self.emit_block_assignment(body, None);
        self.loop_targets.pop();
        self.output.line(&format!("goto {continue_label};"));
        self.output.line(&format!("{continue_label}: ;"));
        if let Some(update) = update {
            self.emit_expression_statement(update);
        }
        self.output.line(&format!("goto {condition_label};"));
        if needs_break_label {
            self.output.line(&format!("{break_label}: ;"));
        }
        self.emit_cleanup_current();
        self.scopes.pop();
        self.output.close("}");
    }

    fn emit_block_value(&mut self, block: &Block, ty: Type) -> String {
        let result = (ty != Type::Unit).then(|| {
            let value = self.new_temporary();
            self.output.line(&format!("{} {value};", c_type(&ty)));
            value
        });
        self.output.open("{");
        self.emit_block_assignment(block, result.as_deref());
        self.output.close("}");
        result.unwrap_or_default()
    }

    fn emit_block_assignment(&mut self, block: &Block, target: Option<&str>) {
        self.output.open("{");
        self.push_scope();
        self.emit_statements(&block.statements);
        if let Some(tail) = block.tail.as_deref() {
            let value = self.emit_value(tail);
            if let Some(target) = target {
                let ty = self.expression_type(tail);
                let value = self.materialize(&ty, value);
                self.output.line(&format!("{target} = {value};"));
            }
        }
        self.emit_cleanup_current();
        self.scopes.pop();
        self.output.close("}");
    }

    fn emit_return(&mut self, value: Option<&Expr>) {
        let return_type = self.info.return_type.clone();
        let value = value.map(|value| {
            let emitted = self.emit_value(value);
            self.materialize(&return_type, emitted)
        });
        if self.info.error_type.is_some() {
            if let Some(value) = value {
                self.output.line(&format!("*out_value = {value};"));
            }
            self.emit_cleanup_from(0);
            self.output.line("return INT32_C(0);");
        } else {
            self.emit_cleanup_from(0);
            if let Some(value) = value {
                self.output.line(&format!("return {value};"));
            } else {
                self.output.line("return;");
            }
        }
    }

    fn emit_raise(&mut self, value: &Expr) {
        let ty = self.expression_type(value);
        let emitted = self.emit_value(value);
        let value = self.materialize(&ty, emitted);
        self.propagate_error(&value);
    }

    fn propagate_error(&mut self, value: &str) {
        if let Some(target) = self.error_targets.last().cloned() {
            self.emit_cleanup_from(target.scope_depth);
            self.output
                .line(&format!("{} = {value};", target.error_variable));
            self.output.line(&format!("goto {};", target.label));
        } else {
            self.emit_cleanup_from(0);
            self.output.line(&format!("*out_error = {value};"));
            self.output.line("return INT32_C(1);");
        }
    }

    fn emit_loop_transfer(&mut self, is_break: bool) {
        let target = self
            .loop_targets
            .last()
            .cloned()
            .expect("validated loop target");
        self.emit_cleanup_from(target.scope_depth);
        self.output.line(&format!(
            "goto {};",
            if is_break {
                target.break_label
            } else {
                target.continue_label
            }
        ));
    }

    fn emit_pattern_bindings(&mut self, pattern: &Pattern, value: &str, ty: &Type) {
        match pattern {
            Pattern::Bind(name, _) => {
                self.output
                    .line(&format!("{} {} = {value};", c_type(ty), local_name(name)));
            }
            Pattern::NonNull(name, _) => {
                let Type::Pointer {
                    mutable, pointee, ..
                } = ty
                else {
                    return;
                };
                let nonnull = Type::Pointer {
                    nullable: false,
                    mutable: *mutable,
                    pointee: pointee.clone(),
                };
                self.output.line(&format!(
                    "{} {} = {value};",
                    c_type(&nonnull),
                    local_name(name)
                ));
            }
            Pattern::Variant(path, patterns, _) => {
                if let Some((_, variant)) = split_variant(path) {
                    for (index, pattern) in patterns.iter().enumerate() {
                        let payload_type = match ty {
                            Type::Enum(enum_name) => self
                                .analysis
                                .model
                                .enums
                                .get(enum_name)
                                .and_then(|info| info.variants.get(variant))
                                .and_then(|payload| payload.get(index))
                                .cloned()
                                .unwrap_or(Type::Unknown),
                            _ => Type::Unknown,
                        };
                        self.emit_pattern_bindings(
                            pattern,
                            &format!("({value}).payload.{}._{index}", sanitize(variant)),
                            &payload_type,
                        );
                    }
                }
            }
            Pattern::Struct(path, fields, _) => {
                if let Some(info) = path
                    .first()
                    .and_then(|name| self.analysis.model.structs.get(name))
                {
                    let field_types = info.fields.clone();
                    for field in fields {
                        if let Some(field_type) = field_types.get(&field.name) {
                            let field_value = format!("({value}).{}", local_name(&field.name));
                            if let Some(pattern) = &field.pattern {
                                self.emit_pattern_bindings(pattern, &field_value, field_type);
                            } else {
                                self.output.line(&format!(
                                    "{} {} = {field_value};",
                                    c_type(field_type),
                                    local_name(&field.name)
                                ));
                            }
                        }
                    }
                }
            }
            _ => {}
        }
    }

    fn emit_place(&mut self, expression: &Expr) -> String {
        match &expression.kind {
            ExprKind::Path(path) => self.emit_path(path),
            ExprKind::Unary {
                operator: UnaryOp::Dereference,
                value,
            } => format!("*({})", self.emit_value(value)),
            ExprKind::Field {
                base,
                name,
                pointer,
            } => format!(
                "({}){}{}",
                self.emit_place(base),
                if *pointer { "->" } else { "." },
                local_name(name)
            ),
            _ => self.emit_value(expression),
        }
    }

    fn materialize(&mut self, ty: &Type, value: String) -> String {
        if *ty == Type::Unit || value.is_empty() {
            return value;
        }
        let temporary = self.new_temporary();
        self.output
            .line(&format!("{} {temporary} = {value};", c_type(ty)));
        temporary
    }

    fn push_scope(&mut self) {
        self.scopes.push(Vec::new());
    }

    fn emit_cleanup_current(&mut self) {
        let depth = self.scopes.len().saturating_sub(1);
        self.emit_cleanup_from(depth);
    }

    fn emit_cleanup_from(&mut self, depth: usize) {
        let blocks: Vec<_> = self
            .scopes
            .iter()
            .skip(depth)
            .rev()
            .flat_map(|scope| scope.iter().rev().cloned())
            .collect();
        for block in blocks {
            self.output.open("{");
            self.push_scope();
            self.emit_statements(&block.statements);
            if let Some(tail) = block.tail.as_deref() {
                self.emit_expression_statement(tail);
            }
            self.emit_cleanup_current();
            self.scopes.pop();
            self.output.close("}");
        }
    }

    fn expression_type(&self, expression: &Expr) -> Type {
        self.analysis
            .model
            .expression_types
            .get(&expression.id)
            .cloned()
            .unwrap_or(Type::Unknown)
    }

    fn new_temporary(&mut self) -> String {
        let value = format!("altc_tmp_{}", self.temporary);
        self.temporary += 1;
        value
    }

    fn new_label(&mut self, purpose: &str) -> String {
        let value = format!("altc_{purpose}_{}", self.label);
        self.label += 1;
        value
    }

    fn error(&mut self, code: &str, message: impl Into<String>, span: Span) {
        self.diagnostics.push(Diagnostic::error(
            code,
            message,
            &self.analysis.source.path,
            &self.analysis.source.text,
            span,
        ));
    }
}

#[derive(Default)]
struct Writer {
    text: String,
    indent: usize,
}

impl Writer {
    fn line(&mut self, line: &str) {
        if !line.is_empty() {
            self.text.push_str(&"  ".repeat(self.indent));
            self.text.push_str(line);
        }
        self.text.push('\n');
    }

    fn open(&mut self, line: &str) {
        self.line(line);
        self.indent += 1;
    }

    fn close(&mut self, line: &str) {
        self.indent = self.indent.saturating_sub(1);
        self.line(line);
    }

    fn reopen(&mut self, line: &str) {
        self.indent = self.indent.saturating_sub(1);
        self.line(line);
        self.indent += 1;
    }

    fn finish(self) -> String {
        self.text
    }
}

fn function_signature(info: &FunctionInfo, function: &Function) -> String {
    let storage = if info.export_c { "" } else { "static " };
    let signature = if info.error_type.is_some() {
        raising_signature(info, function, function_c_name(info))
    } else {
        normal_signature(info, function, function_c_name(info))
    };
    format!("{storage}{signature}")
}

fn exported_signature(info: &FunctionInfo, function: &Function) -> String {
    if info.error_type.is_some() {
        raising_signature(info, function, info.c_name.clone())
    } else {
        normal_signature(info, function, info.c_name.clone())
    }
}

fn normal_signature(info: &FunctionInfo, function: &Function, name: String) -> String {
    let parameters = function
        .parameters
        .iter()
        .zip(&info.parameters)
        .map(|(parameter, ty)| format!("{} {}", c_type(ty), local_name(&parameter.name)))
        .collect::<Vec<_>>();
    format!(
        "{} {name}({})",
        c_type(&info.return_type),
        if parameters.is_empty() {
            "void".to_owned()
        } else {
            parameters.join(", ")
        }
    )
}

fn raising_signature(info: &FunctionInfo, function: &Function, name: String) -> String {
    let mut parameters = function
        .parameters
        .iter()
        .zip(&info.parameters)
        .map(|(parameter, ty)| format!("{} {}", c_type(ty), local_name(&parameter.name)))
        .collect::<Vec<_>>();
    if info.return_type != Type::Unit {
        parameters.push(format!("{} *out_value", c_type(&info.return_type)));
    }
    parameters.push(format!(
        "{} *out_error",
        c_type(info.error_type.as_ref().expect("raising signature"))
    ));
    format!("int32_t {name}({})", parameters.join(", "))
}

fn function_c_name(info: &FunctionInfo) -> String {
    if info.export_c || info.is_extern {
        info.c_name.clone()
    } else {
        format!("altc_fn_{}", sanitize(&info.name))
    }
}

fn resolve_type(model: &SemanticModel, reference: &TypeRef) -> Type {
    match reference {
        TypeRef::Named { path, .. } if path.len() == 1 => {
            crate::semantics::primitive_type(&path[0])
                .or_else(|| {
                    let name = &path[0];
                    if model.structs.contains_key(name) {
                        Some(Type::Struct(name.to_owned()))
                    } else if model.enums.contains_key(name) {
                        Some(Type::Enum(name.to_owned()))
                    } else if model.opaque_types.contains_key(name) {
                        Some(Type::Opaque(model.opaque_types[name].clone()))
                    } else {
                        None
                    }
                })
                .unwrap_or(Type::Unknown)
        }
        TypeRef::Pointer {
            nullable,
            mutable,
            pointee,
            ..
        } => Type::Pointer {
            nullable: *nullable,
            mutable: *mutable,
            pointee: Box::new(resolve_type(model, pointee)),
        },
        _ => Type::Unknown,
    }
}

fn c_type(ty: &Type) -> String {
    match ty {
        Type::Unit => "void".to_owned(),
        Type::Bool => "bool".to_owned(),
        Type::Int(IntType::I8) => "int8_t".to_owned(),
        Type::Int(IntType::I16) => "int16_t".to_owned(),
        Type::Int(IntType::I32) => "int32_t".to_owned(),
        Type::Int(IntType::I64) => "int64_t".to_owned(),
        Type::Int(IntType::U8) => "uint8_t".to_owned(),
        Type::Int(IntType::U16) => "uint16_t".to_owned(),
        Type::Int(IntType::U32) => "uint32_t".to_owned(),
        Type::Int(IntType::U64) => "uint64_t".to_owned(),
        Type::Int(IntType::Isize) => "ptrdiff_t".to_owned(),
        Type::Int(IntType::Usize) => "size_t".to_owned(),
        Type::Int(IntType::CChar) => "char".to_owned(),
        Type::Int(IntType::CSChar) => "signed char".to_owned(),
        Type::Int(IntType::CUChar) => "unsigned char".to_owned(),
        Type::Int(IntType::CShort) => "short".to_owned(),
        Type::Int(IntType::CUShort) => "unsigned short".to_owned(),
        Type::Int(IntType::CInt) => "int".to_owned(),
        Type::Int(IntType::CUInt) => "unsigned int".to_owned(),
        Type::Int(IntType::CLong) => "long".to_owned(),
        Type::Int(IntType::CULong) => "unsigned long".to_owned(),
        Type::Int(IntType::CLongLong) => "long long".to_owned(),
        Type::Int(IntType::CULongLong) => "unsigned long long".to_owned(),
        Type::Float(FloatType::F32) => "float".to_owned(),
        Type::Float(FloatType::F64) => "double".to_owned(),
        Type::Float(FloatType::CFloat) => "float".to_owned(),
        Type::Float(FloatType::CDouble) => "double".to_owned(),
        Type::Float(FloatType::CLongDouble) => "long double".to_owned(),
        Type::Char => "uint32_t".to_owned(),
        Type::Str => "altc_str".to_owned(),
        Type::Pointer {
            mutable, pointee, ..
        } => {
            if **pointee == Type::Unit {
                if *mutable {
                    "void *".to_owned()
                } else {
                    "const void *".to_owned()
                }
            } else if *mutable {
                format!("{} *", c_type(pointee))
            } else {
                format!("const {} *", c_type(pointee))
            }
        }
        Type::Struct(name) | Type::Enum(name) => type_name(name),
        Type::Opaque(name) => name.clone(),
        Type::Never | Type::Unknown => "int32_t".to_owned(),
    }
}

